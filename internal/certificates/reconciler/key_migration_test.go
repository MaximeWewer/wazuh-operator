// TestMigrateKeyToPKCS8 asserts a PKCS#1 key (generated by older operators, rejected by
// the 4.14+ indexer) is rewritten in PKCS#8 for the same key, and a PKCS#8 or unparsable
// key is left untouched.
func TestMigrateKeyToPKCS8(t *testing.T) {
	key, err := rsa.GenerateKey(rand.Reader, 2048)
	if err != nil {
		t.Fatal(err)
	}
	pkcs1 := pem.EncodeToMemory(&pem.Block{Type: "RSA PRIVATE KEY", Bytes: x509.MarshalPKCS1PrivateKey(key)})
	der, _ := x509.MarshalPKCS8PrivateKey(key)
	pkcs8 := pem.EncodeToMemory(&pem.Block{Type: "PRIVATE KEY", Bytes: der})

	for name, tc := range map[string]struct{ in, want []byte }{
		"PKCS#1 is migrated":     {pkcs1, pkcs8},
		"PKCS#8 is kept":         {pkcs8, pkcs8},
		"unparsable key is kept": {[]byte("garbage"), []byte("garbage")},
	} {
		t.Run(name, func(t *testing.T) {
			scheme := runtime.NewScheme()
			_ = corev1.AddToScheme(scheme)
			secret := &corev1.Secret{
				ObjectMeta: metav1.ObjectMeta{Name: "c-indexer-certs", Namespace: "ns"},
				Data:       map[string][]byte{constants.SecretKeyTLSKey: tc.in},
			}
			c := fake.NewClientBuilder().WithScheme(scheme).WithObjects(secret).Build()
			r := NewCertificateReconciler(c, scheme)
			found := &corev1.Secret{}
			if err := c.Get(context.Background(), types.NamespacedName{Name: "c-indexer-certs", Namespace: "ns"}, found); err != nil {
				t.Fatal(err)
			}
			if err := r.migrateKeyToPKCS8(context.Background(), found); err != nil {
				t.Fatal(err)
			}
			got := &corev1.Secret{}
			if err := c.Get(context.Background(), types.NamespacedName{Name: "c-indexer-certs", Namespace: "ns"}, got); err != nil {
				t.Fatal(err)
			}
			if string(got.Data[constants.SecretKeyTLSKey]) != string(tc.want) {
				t.Errorf("tls.key = %q, want %q", got.Data[constants.SecretKeyTLSKey], tc.want)
			}
		})
	}
}
