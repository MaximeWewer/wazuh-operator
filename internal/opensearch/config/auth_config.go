// formatConfigMap formats a map for YAML output with proper indentation
func formatConfigMap(config map[string]any, indent int) string {
	var sb strings.Builder
	prefix := strings.Repeat(" ", indent)

	// Sort keys for consistent output
	keys := make([]string, 0, len(config))
	for k := range config {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	for _, key := range keys {
		value := config[key]
		switch v := value.(type) {
		case string:
			if strings.Contains(v, "\n") || strings.Contains(v, ":") || strings.Contains(v, "#") {
				fmt.Fprintf(&sb, "%s%s: \"%s\"\n", prefix, key, v)
			} else {
				fmt.Fprintf(&sb, "%s%s: %s\n", prefix, key, v)
			}
		case bool:
			fmt.Fprintf(&sb, "%s%s: %t\n", prefix, key, v)
		case int:
			fmt.Fprintf(&sb, "%s%s: %d\n", prefix, key, v)
		case []string:
			fmt.Fprintf(&sb, "%s%s:\n", prefix, key)
			for _, item := range v {
				fmt.Fprintf(&sb, "%s  - \"%s\"\n", prefix, item)
			}
		case map[string]any:
			fmt.Fprintf(&sb, "%s%s:\n", prefix, key)
			sb.WriteString(formatConfigMap(v, indent+2))
		default:
			fmt.Fprintf(&sb, "%s%s: %v\n", prefix, key, v)
		}
	}

	return sb.String()
}

// GetActiveAuthMethods returns a list of enabled authentication method names
func (b *AuthConfigBuilder) GetActiveAuthMethods() []string {
	var methods []string

	if b.authConfig.BasicAuth != nil && b.authConfig.BasicAuth.Enabled {
		methods = append(methods, "basic")
	}
	if b.authConfig.OIDC != nil && b.authConfig.OIDC.Enabled {
		methods = append(methods, "oidc")
	}
	if b.authConfig.SAML != nil && b.authConfig.SAML.Enabled {
		methods = append(methods, "saml")
	}
	if b.authConfig.LDAP != nil && b.authConfig.LDAP.Enabled {
		methods = append(methods, "ldap")
	}

	return methods
}

// ValidateChallengeSettings checks that only one auth domain has challenge=true
func (b *AuthConfigBuilder) ValidateChallengeSettings() error {
	challengeCount := 0

	if b.authConfig.BasicAuth != nil && b.authConfig.BasicAuth.Enabled && b.authConfig.BasicAuth.Challenge {
		challengeCount++
	}
	if b.authConfig.OIDC != nil && b.authConfig.OIDC.Enabled && b.authConfig.OIDC.Challenge {
		challengeCount++
	}
	if b.authConfig.SAML != nil && b.authConfig.SAML.Enabled && b.authConfig.SAML.Challenge {
		challengeCount++
	}
	if b.authConfig.LDAP != nil && b.authConfig.LDAP.Enabled && b.authConfig.LDAP.Challenge {
		challengeCount++
	}

	if challengeCount > 1 {
		return fmt.Errorf("only one authentication domain can have challenge=true, found %d", challengeCount)
	}

	return nil
}

// ValidateMultiAuthRequiresBasic enforces the constraint from
// security-dashboards-plugin (server/index.ts) that rejects any
// opensearch_security.auth.type array longer than one entry unless it
// contains "basicauth". Emitting such an array would make the dashboard
// fail to start on OpenSearch 2.13 through 2.19 with
// "Authentication type is not configured properly. basicauth is mandatory.".
func (b *AuthConfigBuilder) ValidateMultiAuthRequiresBasic() error {
	enabled := 0
	if b.authConfig.OIDC != nil && b.authConfig.OIDC.Enabled {
		enabled++
	}
	if b.authConfig.SAML != nil && b.authConfig.SAML.Enabled {
		enabled++
	}
	basicOn := b.authConfig.BasicAuth != nil && b.authConfig.BasicAuth.Enabled
	if basicOn {
		enabled++
	}
	if enabled > 1 && !basicOn {
		return fmt.Errorf("when more than one dashboard auth method is enabled, basicAuth.enabled must be true (opensearch-dashboards requires basicauth in auth.type array)")
	}
	return nil
}
